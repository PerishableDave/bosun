// Service defaults.
const (
	DefaultLaunchdLabel = "com.github.perishabledave.bosun"
	DefaultSystemdUnit  = "bosund"
	ServiceUser         = "bosun"
	serviceLogFile      = "bosund.log"
	// legacyLaunchdLabel is the label pre-release builds used. Installing
	// under the default label removes an agent left over with this one, so
	// two copies of bosund never compete for the listen port.
	legacyLaunchdLabel = "dev.bosun.bosund"
	// launchdPath is the PATH launchd gives bosund (launchd's own default
	// is only /usr/bin:/bin:/usr/sbin:/sbin, which misses Homebrew tools
	// that MCP servers often need). It is not a secret.
	launchdPath = "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
)

var labelRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$`)

// serviceSpec is everything a launchd plist or systemd unit is generated
// from.
type serviceSpec struct {
	Label   string // launchd label, or systemd unit name without .service
	Bosund  string // absolute path of the bosund binary
	Config  string // absolute path of bosun.yaml
	DataDir string
	LogFile string
	System  bool // systemd system unit running as ServiceUser
}

func xmlEscape(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// launchdPlist renders the launchd user agent. It holds no secrets: bosund
// reads $data_dir/env itself.
func launchdPlist(s serviceSpec) []byte {
	var b strings.Builder
	str := func(v string) string { return "<string>" + xmlEscape(v) + "</string>" }
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ` + "`bosun service install`" + `. Do not put secrets here: bosund loads
     $data_dir/env (mode 0600) itself, and API keys can live in the vault. -->
<plist version="1.0">
<dict>
`)
	fmt.Fprintf(&b, "\t<key>Label</key>\n\t%s\n", str(s.Label))
	fmt.Fprintf(&b, "\t<key>ProgramArguments</key>\n\t<array>\n\t\t%s\n\t\t%s\n\t\t%s\n\t</array>\n", str(s.Bosund), str("--config"), str(s.Config))
	b.WriteString("\t<key>RunAtLoad</key>\n\t<true/>\n")
	// Always keep it running (`bosun service stop` unloads it instead of
	// killing it). A KeepAlive dict such as {SuccessfulExit: false} makes
	// launchd treat the load-time start as "speculative" and defer it.
	b.WriteString("\t<key>KeepAlive</key>\n\t<true/>\n")
	b.WriteString("\t<key>ThrottleInterval</key>\n\t<integer>10</integer>\n")
	fmt.Fprintf(&b, "\t<key>WorkingDirectory</key>\n\t%s\n", str(s.DataDir))
	fmt.Fprintf(&b, "\t<key>StandardOutPath</key>\n\t%s\n", str(s.LogFile))
	fmt.Fprintf(&b, "\t<key>StandardErrorPath</key>\n\t%s\n", str(s.LogFile))
	b.WriteString("\t<key>Umask</key>\n\t<integer>63</integer>\n") // 0077
	fmt.Fprintf(&b, "\t<key>EnvironmentVariables</key>\n\t<dict>\n\t\t<key>PATH</key>\n\t\t%s\n\t</dict>\n", str(launchdPath))
	b.WriteString("</dict>\n</plist>\n")
	return []byte(b.String())
}

// systemdQuote quotes one ExecStart word.
func systemdQuote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	return `"` + r.Replace(s) + `"`
}

// systemdUnit renders the systemd unit (user unit, or with System a system
// unit running as ServiceUser).
func systemdUnit(s serviceSpec) []byte {
	var b strings.Builder
	b.WriteString("# Generated by `bosun service install`. Do not put secrets here: bosund loads\n")
	b.WriteString("# $data_dir/env (mode 0600) itself, and API keys can live in the vault.\n")
	b.WriteString("[Unit]\nDescription=Bosun personal agent daemon (bosund)\nDocumentation=https://github.com/perishabledave/bosun\n")
	b.WriteString("After=network-online.target\nWants=network-online.target\n\n[Service]\nType=simple\n")
	fmt.Fprintf(&b, "ExecStart=%s --config %s\n", systemdQuote(s.Bosund), systemdQuote(s.Config))
	fmt.Fprintf(&b, "WorkingDirectory=%s\n", systemdQuote(s.DataDir))
	b.WriteString("Restart=on-failure\nRestartSec=5\nUMask=0077\nNoNewPrivileges=true\n")
	if s.System {
		fmt.Fprintf(&b, "User=%s\nGroup=%s\n", ServiceUser, ServiceUser)
		b.WriteString("ProtectSystem=full\nPrivateTmp=true\n")
		fmt.Fprintf(&b, "ReadWritePaths=%s\n", systemdQuote(s.DataDir))
		b.WriteString("\n[Install]\nWantedBy=multi-user.target\n")
	} else {
		b.WriteString("\n[Install]\nWantedBy=default.target\n")
	}
	return []byte(b.String())
}

// runner runs service-manager commands (launchctl, systemctl). Tests fake it.
type runner func(ctx context.Context, name string, args ...string) ([]byte, error)

func execRunner(ctx context.Context, name string, args ...string) ([]byte, error) {
	out, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg != "" {
			return out, fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, msg)
		}
		return out, fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	}
	return out, nil
}

// serviceCtl installs and drives the service on one platform.
type serviceCtl struct {
	goos string // "darwin" or "linux"
	home string
	uid  int
	euid int
	spec serviceSpec
	run  runner
	out  io.Writer
	// health reports the daemon's version at the configured address.
	health func(ctx context.Context) (string, error)
}

// unitPath is where the plist or unit file goes.
func (c *serviceCtl) unitPath() string {
	switch {
	case c.goos == "darwin":
		return filepath.Join(c.home, "Library", "LaunchAgents", c.spec.Label+".plist")
	case c.spec.System:
		return filepath.Join("/etc/systemd/system", c.spec.Label+".service")
	default:
		return filepath.Join(c.home, ".config", "systemd", "user", c.spec.Label+".service")
	}
}

func (c *serviceCtl) unitContent() []byte {
	if c.goos == "darwin" {
		return launchdPlist(c.spec)
	}
	return systemdUnit(c.spec)
}

func (c *serviceCtl) kind() string {
	switch {
	case c.goos == "darwin":
		return "launchd user agent"
	case c.spec.System:
		return "systemd system service"
	default:
		return "systemd user service"
	}
}

// launchd helpers.
func (c *serviceCtl) domain() string   { return "gui/" + strconv.Itoa(c.uid) }
func (c *serviceCtl) target() string   { return c.domain() + "/" + c.spec.Label }
func (c *serviceCtl) unitName() string { return c.spec.Label + ".service" }

func (c *serviceCtl) systemctl(ctx context.Context, args ...string) ([]byte, error) {
	if !c.spec.System {
		args = append([]string{"--user"}, args...)
	}
	return c.run(ctx, "systemctl", args...)
}

func (c *serviceCtl) loaded(ctx context.Context) bool {
	_, err := c.run(ctx, "launchctl", "print", c.target())
	return err == nil
}

// bootstrap loads the launchd job and starts it: launchd may defer the
// RunAtLoad start of a freshly bootstrapped agent, so kickstart it too.
func (c *serviceCtl) bootstrap(ctx context.Context) error {
	if _, err := c.run(ctx, "launchctl", "bootstrap", c.domain(), c.unitPath()); err != nil {
		return err
	}
	_, err := c.run(ctx, "launchctl", "kickstart", c.target())
	return err
}

// bootout unloads the launchd job and waits (up to 10s) until launchd has
// let go of it: bootout returns before the job is gone, and an immediate
// bootstrap then fails with "Bootstrap failed: 5: Input/output error".
func (c *serviceCtl) bootout(ctx context.Context) error {
	if _, err := c.run(ctx, "launchctl", "bootout", c.target()); err != nil {
		return err
	}
	for range 100 {
		if !c.loaded(ctx) {
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(100 * time.Millisecond):
		}
	}
	return fmt.Errorf("launchd still has %s loaded after bootout", c.spec.Label)
}

func (c *serviceCtl) install(ctx context.Context) error {
	path := c.unitPath()
	if c.spec.System && c.euid != 0 {
		return fmt.Errorf("writing %s needs root: run it with sudo (`sudo bosun service install --system --config %s`), or pass --print to see the unit", path, c.spec.Config)
	}
	if err := os.MkdirAll(filepath.Dir(c.spec.LogFile), 0o700); err != nil {
		return fmt.Errorf("create log dir: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	if err := writeFileAtomic(path, c.unitContent(), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(c.out, "Wrote %s (%s)\n", path, c.kind())
	switch c.goos {
	case "darwin":
		if err := c.removeLegacyAgent(ctx); err != nil {
			return err
		}
		if c.loaded(ctx) {
			if err := c.bootout(ctx); err != nil {
				return err
			}
		}
		if err := c.bootstrap(ctx); err != nil {
			return err
		}
		fmt.Fprintf(c.out, "Loaded %s; it starts now and at every login. Logs: %s\n", c.spec.Label, c.spec.LogFile)
	default:
		if _, err := c.systemctl(ctx, "daemon-reload"); err != nil {
			return err
		}
		if _, err := c.systemctl(ctx, "enable", "--now", c.unitName()); err != nil {
			return err
		}
		fmt.Fprintf(c.out, "Enabled and started %s.\n", c.unitName())
		if c.spec.System {
			fmt.Fprintf(c.out, "It runs as the %q user, which needs read access to %s and ownership of %s.\n", ServiceUser, c.spec.Config, c.spec.DataDir)
		} else {
			fmt.Fprintln(c.out, "To keep it running after you log out (and start it at boot), run once:")
			fmt.Fprintf(c.out, "  sudo loginctl enable-linger %s\n", currentUsername())
		}
	}
	fmt.Fprintln(c.out, "Secrets (API keys, tokens) go in the vault (`bosun credentials set ...`) or in")
	fmt.Fprintf(c.out, "%s (KEY=VALUE lines, mode 0600), never in the unit file.\n", filepath.Join(c.spec.DataDir, "env"))
	return nil
}

// removeLegacyAgent unloads and deletes a launchd agent installed under
// legacyLaunchdLabel, when installing under the default label.
func (c *serviceCtl) removeLegacyAgent(ctx context.Context) error {
	if c.spec.Label != DefaultLaunchdLabel {
		return nil
	}
	old := filepath.Join(c.home, "Library", "LaunchAgents", legacyLaunchdLabel+".plist")
	if _, err := os.Stat(old); err != nil {
		return nil
	}
	target := c.domain() + "/" + legacyLaunchdLabel
	if _, err := c.run(ctx, "launchctl", "print", target); err == nil {
		if _, err := c.run(ctx, "launchctl", "bootout", target); err != nil {
			return fmt.Errorf("unload the old agent %s: %w", legacyLaunchdLabel, err)
		}
	}
	if err := os.Remove(old); err != nil {
		return fmt.Errorf("remove the old agent: %w", err)
	}
	fmt.Fprintf(c.out, "Removed the old agent %s (%s).\n", legacyLaunchdLabel, old)
	return nil
}

func (c *serviceCtl) uninstall(ctx context.Context) error {
	path := c.unitPath()
	switch c.goos {
	case "darwin":
		if c.loaded(ctx) {
			if err := c.bootout(ctx); err != nil {
				return err
			}
		}
	default:
		if _, err := os.Stat(path); err == nil {
			_, _ = c.systemctl(ctx, "disable", "--now", c.unitName())
		}
	}
	err := os.Remove(path)
	if errors.Is(err, fs.ErrNotExist) {
		fmt.Fprintf(c.out, "%s is not installed (%s does not exist).\n", c.spec.Label, path)
		return nil
	}
	if err != nil {
		return fmt.Errorf("remove %s: %w", path, err)
	}
	if c.goos != "darwin" {
		_, _ = c.systemctl(ctx, "daemon-reload")
	}
	fmt.Fprintf(c.out, "Removed %s. Your config, data, and logs are untouched.\n", path)
	return nil
}

func (c *serviceCtl) requireInstalled() error {
	if _, err := os.Stat(c.unitPath()); err != nil {
		return fmt.Errorf("%s is not installed (run `bosun service install`)", c.spec.Label)
	}
	return nil
}

func (c *serviceCtl) start(ctx context.Context) error {
	if err := c.requireInstalled(); err != nil {
		return err
	}
	if c.goos == "darwin" {
		var err error
		if c.loaded(ctx) {
			_, err = c.run(ctx, "launchctl", "kickstart", c.target())
		} else {
			err = c.bootstrap(ctx)
		}
		if err != nil {
			return err
		}
	} else if _, err := c.systemctl(ctx, "start", c.unitName()); err != nil {
		return err
	}
	fmt.Fprintf(c.out, "Started %s.\n", c.spec.Label)
	return nil
}

func (c *serviceCtl) stop(ctx context.Context) error {
	if c.goos == "darwin" {
		// Unload it: with KeepAlive a killed agent could be restarted.
		// It loads again at next login or with `bosun service start`.
		if !c.loaded(ctx) {
			fmt.Fprintf(c.out, "%s is not running.\n", c.spec.Label)
			return nil
		}
		if err := c.bootout(ctx); err != nil {
			return err
		}
	} else if _, err := c.systemctl(ctx, "stop", c.unitName()); err != nil {
		return err
	}
	fmt.Fprintf(c.out, "Stopped %s.\n", c.spec.Label)
	return nil
}

func (c *serviceCtl) restart(ctx context.Context) error {
	if err := c.requireInstalled(); err != nil {
		return err
	}
	if c.goos == "darwin" {
		var err error
		if c.loaded(ctx) {
			_, err = c.run(ctx, "launchctl", "kickstart", "-k", c.target())
		} else {
			err = c.bootstrap(ctx)
		}
		if err != nil {
			return err
		}
	} else if _, err := c.systemctl(ctx, "restart", c.unitName()); err != nil {
		return err
	}
	fmt.Fprintf(c.out, "Restarted %s.\n", c.spec.Label)
	return nil
}

var (
	// Top-level job properties are indented by exactly one tab; nested
	// blocks (endpoints, ...) have their own "state = " lines.
	launchdStateRe = regexp.MustCompile(`(?m)^\tstate = (.+)$`)
	launchdPIDRe   = regexp.MustCompile(`(?m)^\tpid = (\d+)`)
	launchdExitRe  = regexp.MustCompile(`(?m)^\tlast exit code = (.+)$`)
)

// state returns a one-line description of the service manager's view.
func (c *serviceCtl) state(ctx context.Context) (string, bool) {
	if c.goos == "darwin" {
		out, err := c.run(ctx, "launchctl", "print", c.target())
		if err != nil {
			return "not loaded", false
		}
		state, pid, exit := "unknown", "", ""
		if m := launchdStateRe.FindSubmatch(out); m != nil {
			state = strings.TrimSpace(string(m[1]))
		}
		if m := launchdPIDRe.FindSubmatch(out); m != nil {
			pid = string(m[1])
		}
		if m := launchdExitRe.FindSubmatch(out); m != nil {
			exit = strings.TrimSpace(string(m[1]))
		}
		s := state
		if pid != "" {
			s += " (pid " + pid + ")"
		}
		if exit != "" && state != "running" {
			s += ", last exit code " + exit
		}
		return s, state == "running"
	}
	out, err := c.systemctl(ctx, "show", c.unitName(), "--property=LoadState,ActiveState,SubState,MainPID")
	if err != nil {
		return "unknown: " + err.Error(), false
	}
	props := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		if k, v, ok := strings.Cut(strings.TrimSpace(line), "="); ok {
			props[k] = v
		}
	}
	if props["LoadState"] == "not-found" {
		return "not loaded", false
	}
	s := props["ActiveState"] + " (" + props["SubState"] + ")"
	if pid := props["MainPID"]; pid != "" && pid != "0" {
		s += ", pid " + pid
	}
	return s, props["ActiveState"] == "active"
}

func (c *serviceCtl) status(ctx context.Context) error {
	path := c.unitPath()
	installed := "installed"
	if _, err := os.Stat(path); err != nil {
		installed = "not installed"
	}
	st, _ := c.state(ctx)
	fmt.Fprintf(c.out, "service  %s (%s)\n", c.spec.Label, c.kind())
	fmt.Fprintf(c.out, "unit     %s (%s)\n", path, installed)
	fmt.Fprintf(c.out, "state    %s\n", st)
	if c.health != nil {
		hctx, cancel := context.WithTimeout(ctx, 5*time.Second)
		v, err := c.health(hctx)
		cancel()
		if err != nil {
			fmt.Fprintf(c.out, "daemon   not responding: %v\n", err)
		} else {
			fmt.Fprintf(c.out, "daemon   healthy, bosund %s\n", v)
		}
	}
	if c.goos == "darwin" {
		fmt.Fprintf(c.out, "logs     %s\n", c.spec.LogFile)
	} else {
		fmt.Fprintf(c.out, "logs     journalctl %s-u %s\n", map[bool]string{false: "--user ", true: ""}[c.spec.System], c.unitName())
	}
	return nil
}

// logsCommand returns the command `bosun service logs` runs.
func (c *serviceCtl) logsCommand(lines int, follow bool) []string {
	if c.goos == "darwin" {
		args := []string{"tail", "-n", strconv.Itoa(lines)}
		if follow {
			args = append(args, "-F")
		}
		return append(args, c.spec.LogFile)
	}
	args := []string{"journalctl"}
	if !c.spec.System {
		args = append(args, "--user")
	}
	args = append(args, "-u", c.unitName(), "-n", strconv.Itoa(lines))
	if follow {
		args = append(args, "-f")
	}
	return args
}

func writeFileAtomic(path string, b []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	_, werr := tmp.Write(b)
	cerr := tmp.Close()
	if err := errors.Join(werr, cerr, os.Chmod(tmp.Name(), mode)); err != nil {
		os.Remove(tmp.Name())
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		os.Remove(tmp.Name())
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func currentUsername() string {
	if u := os.Getenv("USER"); u != "" {
		return u
	}
	return "$USER"
}

// findBosund returns the absolute bosund path: next to this bosun binary,
// else on $PATH.
func findBosund() (string, error) {
	if exe, err := os.Executable(); err == nil {
		p := filepath.Join(filepath.Dir(exe), "bosund")
		if fi, err := os.Stat(p); err == nil && !fi.IsDir() {
			return p, nil
		}
	}
	p, err := exec.LookPath("bosund")
	if err != nil {
		return "", errors.New("bosund not found next to bosun or on $PATH (pass --bosund /path/to/bosund)")
	}
	return filepath.Abs(p)
}

type serviceFlags struct {
	label, bosund string
	system, print bool
	lines         int
	noFollow      bool
}

// newServiceCtl builds the controller for this platform from flags and
// the config.
func newServiceCtl(g *globals, f *serviceFlags, out io.Writer, needBosund bool) (*serviceCtl, error) {
	goos := runtime.GOOS
	if goos != "darwin" && goos != "linux" {
		return nil, fmt.Errorf("bosun service supports macOS (launchd) and Linux (systemd), not %s", goos)
	}
	if f.system && goos != "linux" {
		return nil, errors.New("--system is for Linux (systemd); on macOS the service is a launchd user agent")
	}
	cfgPath, err := filepath.Abs(g.configPath)
	if err != nil {
		return nil, err
	}
	cfg, err := config.Load(cfgPath)
	if err != nil {
		return nil, fmt.Errorf("%w (run `bosun setup` first)", err)
	}
	label := f.label
	if label == "" {
		label = DefaultLaunchdLabel
		if goos == "linux" {
			label = DefaultSystemdUnit
		}
	}
	if !labelRe.MatchString(label) {
		return nil, fmt.Errorf("--label %q: letters, digits, '.', '_' and '-' only", label)
	}
	bosund := f.bosund
	if bosund == "" && needBosund {
		if bosund, err = findBosund(); err != nil {
			return nil, err
		}
	}
	if bosund != "" {
		if bosund, err = filepath.Abs(bosund); err != nil {
			return nil, err
		}
		if needBosund {
			if fi, err := os.Stat(bosund); err != nil || fi.IsDir() {
				return nil, fmt.Errorf("--bosund %s: not an executable file", bosund)
			}
		}
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return nil, err
	}
	dataDir, err := filepath.Abs(cfg.Daemon.DataDir)
	if err != nil {
		return nil, err
	}
	c := &serviceCtl{
		goos: goos, home: home, uid: os.Getuid(), euid: os.Geteuid(), run: execRunner, out: out,
		spec: serviceSpec{Label: label, Bosund: bosund, Config: cfgPath, DataDir: dataDir,
			LogFile: filepath.Join(dataDir, "logs", serviceLogFile), System: f.system},
	}
	c.health = func(ctx context.Context) (string, error) {
		base, err := g.baseURL()
		if err != nil {
			return "", err
		}
		return daemonVersion(ctx, base)
	}
	return c, nil
}

